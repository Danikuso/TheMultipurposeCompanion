import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const languages = ['es', 'en', 'fr', 'de', 'pt'];
export const normalize = value => value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
export const source = JSON.parse(readFileSync(new URL('./data/game-localization.json', import.meta.url), 'utf8'));
source.groups.microresource.push({ id: 'DigitalDesigns', labels: { en: 'Digital Designs', es: 'Diseños digitales', fr: 'Conceptions numériques', de: 'Digitale Entwürfe', pt: 'Projetos digitais' } });
export const keyFor = (kind, id) => `game-${kind}-${id.toLowerCase().replace(/[^a-z0-9]/g, '')}`;
export const editorial = (scope, lang) => JSON.parse(readFileSync(new URL(`./data/${scope}-editorial.${lang}.json`, import.meta.url), 'utf8'));
export function gameRows(lang) {
  const overrides = editorial('game', lang);
  return Object.entries(source.groups).flatMap(([kind, rows]) => [...new Map(rows.map(row => [keyFor(kind, row.id), row])).values()].map(row => {
    const key = keyFor(kind, row.id);
    const label = overrides[key] ?? row.labels[lang];
    if (!label?.trim()) throw new Error(`Missing translation: ${lang}/${key}`);
    return { kind, id: row.id, key, label, labels: row.labels };
  }));
}
const resourceAliases = new Map();
for (const [kind, rows] of Object.entries(source.groups)) {
  if (!['commodity', 'material', 'microresource'].includes(kind)) continue;
  for (const row of rows) {
    for (const name of [row.labels.en, row.id.replace(/([a-z])([A-Z])/g, '$1 $2')]) {
      if (name && name.length > 2) resourceAliases.set(name, keyFor(kind, row.id));
    }
  }
}
for (const [name, key] of Object.entries({
  'Occupied Escape Pods': 'game-commodity-occupiedcryopod',
  'Insight Entertainment Suites': 'game-microresource-insightentertainmentsuite',
  'Sensor Fragments': 'game-material-unknownenergysource',
  'Xihe Companions': 'game-commodity-xihecompanions',
})) resourceAliases.set(name, key);
const escapeRegex = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const resourcePattern = new RegExp(`\\b(${[...resourceAliases.keys()].sort((a,b) => b.length-a.length).map(escapeRegex).join('|')})\\b`, 'g');
export function localizeGameResources(text) {
  return text.replace(resourcePattern, name => `{ ${resourceAliases.get(name)} }`)
    .replace(/(\d+) (?=\{ game-(?:commodity|material|microresource)-)/g, '$1 × ');
}
export function applyEditorial(text, overrides, skipUnlock = false) {
  const used = new Set();
  const result = text.replace(/^([a-z][a-z0-9_-]*) = ([^\n]*(?:\n[ \t]+[^\n]*)*)/gm, (block, key, value) => {
    if (!(key in overrides) || (skipUnlock && key.startsWith('unlock-'))) return block;
    used.add(key);
    const attributes = value.match(/\n[ \t]+\.[^\n]+/g)?.filter(line => !/^\s*\.pending\s*=/.test(line)) ?? [];
    return `${key} = ${overrides[key]}${attributes.join('')}`;
  });
  return { text: result, used };
}
export function syncGameLocales(check = false) {
  let changes = 0;
  const output = (path, text) => {
    let before;
    try { before = readFileSync(path, 'utf8'); } catch { /* New generated resource. */ }
    if (before === text) return;
    changes++;
    if (!check) writeFileSync(path, text);
    else console.error(`Out of date: ${path}`);
  };
  const index = {};
  for (const row of gameRows('en')) {
    (index[row.kind] ??= {})[normalize(row.id)] = { id: row.id, key: row.key };
  }
  const candidates = new Map();
  for (const lang of languages) {
    const rows = gameRows(lang);
    output(`locales/${lang}/game-data.ftl`, '# Generated by scripts/sync-game-locales.mjs. Apache-2.0 source and TMC editorial translations; see THIRD_PARTY_NOTICES.md.\n' + rows.map(row => `${row.key} = ${row.label}`).join('\n') + '\n');
    for (const row of rows) {
      for (const label of [row.label, row.labels.en, row.id.replace(/([a-z])([A-Z])/g, '$1 $2')]) {
        if (!label) continue;
        const alias = `${row.kind}:${normalize(label)}`;
        if (!candidates.has(alias)) candidates.set(alias, new Map());
        candidates.get(alias).set(row.key, { id: row.id, key: row.key });
      }
    }
    const used = new Set();
    const overrides = Object.fromEntries(Object.entries({ ...editorial('engineering', lang), ...editorial('ui', lang) }).map(([key, value]) => [key, key.startsWith('unlock-') ? localizeGameResources(value) : value]));
    for (const file of readdirSync(`locales/${lang}`).filter(file => file.endsWith('.ftl') && file !== 'game-data.ftl')) {
      const path = `locales/${lang}/${file}`;
      const result = applyEditorial(readFileSync(path, 'utf8').replace(/\r\n/g, '\n'), overrides);
      for (const key of result.used) used.add(key);
      output(path, result.text.replace('# Un nombre sin confirmación oficial en este idioma se deja con su valor en inglés y el atributo .pending = 1.', '# Traducciones completadas mediante revisión editorial TMC; no implican validación oficial de Frontier.'));
    }
    const missing = Object.keys(overrides).filter(key => !used.has(key));
    if (missing.length) throw new Error(`Unknown editorial keys (${lang}): ${missing.join(', ')}`);
  }
  for (const [alias, matches] of candidates) {
    const [kind, name] = alias.split(':');
    if (matches.size === 1 && !index[kind][name]) index[kind][name] = [...matches.values()][0];
  }
  mkdirSync('crates/tmc-i18n/data', { recursive: true });
  output('crates/tmc-i18n/data/game-label-index.json', JSON.stringify(index) + '\n');
  return changes;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changes = syncGameLocales(check);
  console.log(`${changes} locale files ${check ? 'need synchronization' : 'updated'}`);
  if (check && changes) process.exitCode = 1;
}
